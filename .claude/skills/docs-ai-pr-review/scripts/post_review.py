#!/usr/bin/env python3
"""Post docs-ai-pr-review findings as one GitHub review (event COMMENT).

- Checks every finding's line (and start_line) against the PR diff, since
  GitHub only accepts inline comments on lines shown on the new side of a hunk.
- Skips findings already posted on an earlier run (matched by a hidden marker).
- Submits all remaining findings as a single review through the `gh` CLI.

Usage:
  python scripts/post_review.py --repo yamilkar/docs-ai-assistant --pr 3 \
    --findings findings.json --diff pr.diff [--dry-run]
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys

SEVERITIES = ("blocker", "suggestion", "nit")
MAX_NITS = 5
MARKER = "<!-- docs-ai-pr-review:{} -->"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")


def parse_diff(diff_text):
    """Map path -> list of hunks, each hunk a set of commentable new-side lines."""
    files = {}
    path = None
    new_line = None
    for raw in diff_text.splitlines():
        if raw.startswith("diff --git "):
            path, new_line = None, None
        elif raw.startswith("+++ "):
            target = raw[4:].strip()
            path = None if target == "/dev/null" else re.sub(r"^b/", "", target)
            if path:
                files.setdefault(path, [])
        elif raw.startswith("@@") and path:
            match = HUNK_RE.match(raw)
            new_line = int(match.group(1))
            files[path].append(set())
        elif path and new_line is not None and files[path]:
            if raw.startswith("+") or raw.startswith(" ") or raw == "":
                files[path][-1].add(new_line)
                new_line += 1
            # "-" lines exist only on the old side; "\" is "No newline at end of file".
    return files


def finding_key(f):
    text = "|".join(str(f.get(k, "")) for k in ("path", "severity", "principle", "title"))
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def validate(findings, hunks_by_path):
    errors = []
    for i, f in enumerate(findings):
        where = f"finding {i} ({f.get('path')}:{f.get('line')})"
        for field in ("path", "line", "severity", "principle", "title", "body"):
            if not f.get(field):
                errors.append(f"{where}: missing '{field}'")
        if f.get("severity") not in SEVERITIES:
            errors.append(f"{where}: severity must be one of {SEVERITIES}")
        hunks = hunks_by_path.get(f.get("path"))
        if hunks is None:
            errors.append(f"{where}: file is not in the diff")
            continue
        line, start = f.get("line"), f.get("start_line")
        hunk = next((h for h in hunks if line in h), None)
        if hunk is None:
            errors.append(f"{where}: line {line} is not a commentable line in the diff")
        elif start is not None and (start not in hunk or start >= line):
            errors.append(f"{where}: start_line {start} must be before line {line} in the same hunk")
    nits = sum(1 for f in findings if f.get("severity") == "nit")
    if nits > MAX_NITS:
        errors.append(f"{nits} nits; keep at most {MAX_NITS}")
    return errors


def gh(*args, stdin=None):
    result = subprocess.run(["gh", *args], input=stdin, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args)} failed:\n{result.stderr}")
    return result.stdout


def already_posted(repo, pr):
    out = gh("api", "--paginate", f"repos/{repo}/pulls/{pr}/comments", "--jq", ".[].body")
    return set(re.findall(r"<!-- docs-ai-pr-review:([0-9a-f]{16}) -->", out))


def comment_body(f):
    return (
        f"**[{f['severity']}] {f['principle']}**: {f['title']}\n\n{f['body']}"
        f"{FOOTER}\n{MARKER.format(finding_key(f))}"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", required=True)
    parser.add_argument("--pr", required=True, type=int)
    parser.add_argument("--findings", required=True)
    parser.add_argument("--diff", required=True)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    with open(args.findings, encoding="utf-8") as fh:
        findings = json.load(fh).get("comments", [])
    with open(args.diff, encoding="utf-8") as fh:
        hunks_by_path = parse_diff(fh.read())

    errors = validate(findings, hunks_by_path)
    if errors:
        sys.exit("Fix these findings and rerun:\n- " + "\n- ".join(errors))

    posted = set() if args.dry_run else already_posted(args.repo, args.pr)
    new = [f for f in findings if finding_key(f) not in posted]
    skipped = len(findings) - len(new)

    comments = []
    for f in new:
        c = {"path": f["path"], "line": f["line"], "side": "RIGHT", "body": comment_body(f)}
        if f.get("start_line") is not None:
            c.update(start_line=f["start_line"], start_side="RIGHT")
        comments.append(c)

    counts = {s: sum(1 for f in new if f["severity"] == s) for s in SEVERITIES}
    summary = ", ".join(f"{n} {s}" for s, n in counts.items())

    if args.dry_run:
        print(json.dumps(comments, indent=2, ensure_ascii=False))
        print(f"\nDry run: would post {len(comments)} comment(s) ({summary}).")
        return
    if not comments:
        print(f"Nothing new to post ({skipped} already posted).")
        return

    head = gh("pr", "view", str(args.pr), "--repo", args.repo, "--json", "headRefOid", "--jq", ".headRefOid").strip()
    review = {
        "commit_id": head,
        "event": "COMMENT",
        "body": f"Design review: {summary}.{FOOTER}",
        "comments": comments,
    }
    gh("api", "-X", "POST", f"repos/{args.repo}/pulls/{args.pr}/reviews", "--input", "-", stdin=json.dumps(review))
    print(f"Posted {len(comments)} comment(s) ({summary}); skipped {skipped} already posted.")


if __name__ == "__main__":
    main()
