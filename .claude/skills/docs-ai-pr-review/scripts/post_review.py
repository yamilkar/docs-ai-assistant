#!/usr/bin/env python3
"""Post design-review findings as inline comments on a GitHub PR.

Validates every comment's line against the PR diff (GitHub rejects comments on
lines outside the diff), skips findings already posted by an earlier run of this
review, and submits the rest as a single review with the COMMENT event.

Usage:
  python post_review.py --repo OWNER/REPO --pr N --findings findings.json \
      [--diff pr.diff] [--dry-run]

Requires the GitHub CLI (`gh`) authenticated for the repo, except with
--dry-run plus --diff, which needs nothing.
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys

SEVERITIES = ("blocker", "suggestion", "nit")
MAX_NITS = 5
MARKER = "design-review"
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


def gh(*args, stdin=None):
    result = subprocess.run(
        ["gh", *args], input=stdin, capture_output=True, text=True
    )
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args[:3])} failed:\n{result.stderr.strip()}")
    return result.stdout


def commentable_lines(diff_text):
    """Map each file path to {new-side line number: hunk index} for lines in the diff."""
    lines_by_path = {}
    path = None
    new_line = 0
    hunk_index = -1
    hunk = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
    for raw in diff_text.splitlines():
        if raw.startswith("diff --git"):
            path = None
        elif raw.startswith("+++ "):
            target = raw[4:].strip()
            path = None if target == "/dev/null" else re.sub(r"^b/", "", target)
            if path:
                lines_by_path.setdefault(path, {})
        elif raw.startswith("--- "):
            continue
        elif path and (m := hunk.match(raw)):
            new_line = int(m.group(1))
            hunk_index += 1
        elif path and new_line:
            # An empty line is a context line whose leading space was stripped.
            if raw.startswith("+") or raw.startswith(" ") or raw == "":
                lines_by_path[path][new_line] = hunk_index
                new_line += 1
            # "-" lines and "\ No newline" don't advance the new side
    return lines_by_path


def finding_key(c):
    raw = f"{c['path']}|{c['principle']}|{c['title']}".lower()
    return hashlib.sha1(raw.encode()).hexdigest()[:12]


def render_body(c):
    return (
        f"**[{c['severity']}] {c['principle']}**: {c['title']}\n\n"
        f"{c['body'].strip()}\n\n"
        f"{FOOTER}\n"
        f"<!-- {MARKER}:{finding_key(c)} -->"
    )


def validate(comments, lines_by_path):
    errors = []
    for i, c in enumerate(comments):
        label = f"#{i} ({c.get('path')}:{c.get('line')})"
        missing = [k for k in ("path", "line", "severity", "principle", "title", "body") if not c.get(k)]
        if missing:
            errors.append(f"{label}: missing {', '.join(missing)}")
            continue
        if c["severity"] not in SEVERITIES:
            errors.append(f"{label}: severity must be one of {SEVERITIES}")
        valid = lines_by_path.get(c["path"])
        if valid is None:
            errors.append(f"{label}: file is not in the diff")
            continue
        for key in ("start_line", "line"):
            if key in c and c[key] not in valid:
                near = sorted(valid, key=lambda n: abs(n - c[key]))[:3]
                errors.append(f"{label}: {key} {c[key]} is outside the diff; nearest valid lines: {near}")
        if "start_line" in c and c["start_line"] >= c["line"]:
            errors.append(f"{label}: start_line must be before line")
        elif "start_line" in c and c["start_line"] in valid and c["line"] in valid \
                and valid[c["start_line"]] != valid[c["line"]]:
            errors.append(f"{label}: start_line and line must be in the same diff hunk")
    return errors


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--repo", required=True)
    p.add_argument("--pr", required=True, type=int)
    p.add_argument("--findings", required=True)
    p.add_argument("--diff", help="saved output of `gh pr diff N`; fetched if omitted")
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args()

    with open(a.findings, encoding="utf-8") as f:
        comments = json.load(f)["comments"]

    if a.diff:
        with open(a.diff, encoding="utf-8") as f:
            diff_text = f.read()
    else:
        diff_text = gh("pr", "diff", str(a.pr), "--repo", a.repo)

    errors = validate(comments, commentable_lines(diff_text))
    if errors:
        print("Fix these anchors and rerun (nothing was posted):", file=sys.stderr)
        print("\n".join(f"  {e}" for e in errors), file=sys.stderr)
        sys.exit(2)

    nits = [c for c in comments if c["severity"] == "nit"]
    if len(nits) > MAX_NITS:
        sys.exit(f"{len(nits)} nits; keep the {MAX_NITS} that matter most and rerun.")

    # Skip findings already posted by an earlier run.
    already = set()
    if not a.dry_run:
        existing = json.loads(
            gh("api", f"repos/{a.repo}/pulls/{a.pr}/comments", "--paginate", "--slurp")
        )
        for page in existing:
            for ec in page:
                already.update(re.findall(rf"<!-- {MARKER}:(\w+) -->", ec.get("body", "")))
    new = [c for c in comments if finding_key(c) not in already]
    skipped = len(comments) - len(new)

    payload_comments = []
    for c in new:
        item = {"path": c["path"], "line": c["line"], "side": "RIGHT", "body": render_body(c)}
        if "start_line" in c:
            item.update(start_line=c["start_line"], start_side="RIGHT")
        payload_comments.append(item)

    counts = {s: sum(1 for c in new if c["severity"] == s) for s in SEVERITIES}
    summary = ", ".join(f"{n} {s}{'s' if n != 1 else ''}" for s, n in counts.items())

    if a.dry_run:
        for c in payload_comments:
            print(f"--- {c['path']}:{c.get('start_line', c['line'])}-{c['line']}\n{c['body']}\n")
        print(f"DRY RUN: would post {summary}; {skipped} already posted.")
        return

    if not payload_comments:
        print(f"Nothing new to post; {skipped} findings were already on the PR.")
        return

    head = gh("pr", "view", str(a.pr), "--repo", a.repo, "--json", "headRefOid", "-q", ".headRefOid").strip()
    payload = {"commit_id": head, "event": "COMMENT", "comments": payload_comments}
    out = json.loads(
        gh("api", "-X", "POST", f"repos/{a.repo}/pulls/{a.pr}/reviews", "--input", "-",
           stdin=json.dumps(payload))
    )
    print(f"Posted {summary}; {skipped} already posted. {out.get('html_url', '')}")


if __name__ == "__main__":
    main()
